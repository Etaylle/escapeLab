import { existsSync, readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';

/**
 * The Prisma client is generated once per install, by the server's postinstall — Render installs
 * and then builds, and every generation more is time spent for nothing: not by @prisma/client's
 * own install script (it would generate from the repo's root, by a prisma.config.ts there), not
 * by the build.
 */

const ROOT = new URL('../../../', import.meta.url);
const read = (name: string): string => readFileSync(new URL(name, ROOT), 'utf8');

/** The scripts of the package.json at `name`. */
const scriptsOf = (name: string): Record<string, string> =>
  (JSON.parse(read(name)) as { scripts: Record<string, string> }).scripts;

/** The list under `key` in pnpm-workspace.yaml, its items as written. */
function listed(key: string): string[] {
  const lines = read('pnpm-workspace.yaml').split('\n');
  const start = lines.indexOf(`${key}:`);
  const items: string[] = [];
  for (const line of start < 0 ? [] : lines.slice(start + 1)) {
    const item = /^ {2}- '?([^']+)'?$/.exec(line);
    if (item?.[1] === undefined) {
      break;
    }
    items.push(item[1]);
  }
  return items;
}

describe('the Prisma client', () => {
  it('is generated by the server’s postinstall, by no build and no other install script', () => {
    expect(scriptsOf('packages/server/package.json')['postinstall']).toContain('prisma generate');
    expect(scriptsOf('package.json')['build']).not.toContain('prisma generate');
    expect(listed('onlyBuiltDependencies')).toEqual(['@prisma/engines', 'esbuild', 'prisma']);
    expect(listed('ignoredBuiltDependencies')).toEqual(['@prisma/client']);
    expect(existsSync(new URL('prisma.config.ts', ROOT))).toBe(false);
  });
});
